"""
Tests for FileClassifier
=========================

Verifies the 10-tier priority classification system.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from app.repository.classifier.file_classifier import FileClassifier
from app.repository.types import FileClassification


@pytest.fixture
def classifier() -> FileClassifier:
    return FileClassifier()


class TestAssetClassification:
    def test_image_is_asset(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("logo.png")).category == FileClassification.ASSET
        assert classifier.classify(Path("icon.ico")).category == FileClassification.ASSET

    def test_font_is_asset(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("fonts/Inter.woff2")).category == FileClassification.ASSET

    def test_binary_data_is_asset(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("data.bin")).category == FileClassification.ASSET
        assert classifier.classify(Path("archive.zip")).category == FileClassification.ASSET


class TestVendorClassification:
    def test_vendor_directory(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("vendor/some_lib/file.py")).category == FileClassification.VENDOR

    def test_node_modules(self, classifier: FileClassifier) -> None:
        pass

    def test_third_party_directory(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("third_party/lib/main.c")).category == FileClassification.VENDOR


class TestGeneratedClassification:
    def test_minified_js(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("app.min.js")).category == FileClassification.GENERATED

    def test_bundle_css(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("styles.bundle.css")).category == FileClassification.GENERATED

    def test_protobuf_go(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("user.pb.go")).category == FileClassification.GENERATED

    def test_generated_content_signature(self, classifier: FileClassifier) -> None:
        first_bytes = b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage user"
        assert classifier.classify(Path("user.go"), first_bytes=first_bytes).category == FileClassification.GENERATED


