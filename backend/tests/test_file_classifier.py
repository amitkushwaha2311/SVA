class TestDocumentationClassification:
    def test_readme(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("README.md")).category == FileClassification.DOCUMENTATION
        assert classifier.classify(Path("readme")).category == FileClassification.DOCUMENTATION

    def test_license(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("LICENSE")).category == FileClassification.DOCUMENTATION

    def test_docs_directory(self, classifier: FileClassifier) -> None:
        assert classifier.classify(Path("docs/architecture.md")).category == FileClassification.DOCUMENTATION
        # Should not classify non-doc extensions in docs dir as documentation (e.g. scripts)
        assert classifier.classify(Path("docs/generate.py"), language="Python").category != FileClassification.DOCUMENTATION


